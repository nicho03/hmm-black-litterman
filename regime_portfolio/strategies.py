"""Strategies: fixed weights (benchmarks), HMM + Markowitz, HMM + Black-Litterman."""
import numpy as np
from sklearn.covariance import LedoitWolf, MinCovDet

from .base import PortfolioStrategy


class FixedWeights(PortfolioStrategy):
    """Fixed-weight portfolio. weights=None -> 1/N on the risky assets.
    rebalance=True: back to the target weights at every rebalance;
    rebalance=False: buy-and-hold, weights drift with prices."""

    def __init__(self, rets, rf, weights=None, rebalance=False, **kwargs):
        super().__init__(rets, rf, **kwargs)
        self.rebalance = rebalance
        if weights is not None:
            unknown = set(weights) - set(self.assets)
            if unknown:
                raise ValueError(f"Unknown assets: {unknown}")
            w = np.array([weights.get(a, 0.0) for a in self.assets])
            self.w_start = w / w.sum()                     # start already invested

    def allocate(self, t, w_cur):
        return self.w_start.copy() if self.rebalance else w_cur


class HMMStrategy(PortfolioStrategy):
    """Base class of the regime strategies. Refits the HMM every `refit_every` days on the
    history up to t (expanding window) and, at every rebalance, builds (μ, Σ) from the
    probabilities P(s_{t+1} | data up to t)."""

    def __init__(self, rets, rf, model, refit_every=252, **kwargs):
        super().__init__(rets, rf, **kwargs)
        self.model, self.refit_every = model, refit_every
        self._last_fit, self.p_next = None, None

    def allocate(self, t, w_cur):
        if self._last_fit is None or t - self._last_fit >= self.refit_every:
            self.model.fit(self.X[:t])
            self._last_fit = t
            self.on_refit(t)
        self.p_next = self.model.predict_next(self.X[:t])
        mu, Sigma = self.moments(t, self.p_next)
        return self.optimize(mu, Sigma, w_cur, t)

    def on_refit(self, t):
        """Called after every refit of the HMM."""

    def moments(self, t, p):
        """Expected (μ, Σ) of the risky assets, in daily %."""
        raise NotImplementedError

    def regime(self):
        return int(np.argmax(self.p_next))


class MarkowitzHMM(HMMStrategy):
    """Mean-variance with the regime moments.
    use_mixture=False: mean and covariance of the most likely regime;
    use_mixture=True:  moments of the mixture weighted by P(s_{t+1})."""

    def __init__(self, rets, rf, model, use_mixture=False, **kwargs):
        kwargs.setdefault("name", "HMM + Markowitz")
        super().__init__(rets, rf, model, **kwargs)
        self.use_mixture = use_mixture

    def moments(self, t, p):
        if self.use_mixture:
            q, within, between = self.model.mixture_moments(p)
            return q, within + between
        s = int(np.argmax(p))
        return self.model.means[s], self.model.covars[s]


class BlackLittermanHMM(HMMStrategy):
    """Black-Litterman with views generated by the HMM (on the risky assets).

    Prior : μ ~ N(r_f + Π, τΣ_t),  Π = δ_eq Σ_long w_ref,  δ_eq = SR_target / σ(w_ref),  τ = 1/t
            w_ref = 1/N; Σ_long estimated with `prior_cov` on the history up to the last refit
    Views : P = I,  Q = Σ_k p_k μ_k   (mean of the regime mixture)
    Omega : 'statistical'  Σ_k p_k Σ_k/N_k + Σ_k p_k (μ_k − Q)(μ_k − Q)'  (estimation + regime)
            'conditional'  most likely regime s:  Q = μ_s,  Σ_t = Σ_s,  Ω = Σ_s / N_s
            'idzorek'      Ω = α Σ_t,  α = τ (1 − c) / c,  c = confidence
    """

    PRIOR_COVS = {
        "sample": lambda X: np.cov(X, rowvar=False),
        "ledoit_wolf": lambda X: LedoitWolf().fit(X).covariance_,
        "mcd": lambda X: MinCovDet(support_fraction=0.95, random_state=0).fit(X).covariance_,
    }
    OMEGAS = ("statistical", "conditional", "idzorek")

    def __init__(self, rets, rf, model, omega="statistical", prior_cov="sample",
                 sr_target=0.35, confidence=0.5, **kwargs):
        if omega not in self.OMEGAS or prior_cov not in self.PRIOR_COVS:
            raise ValueError(f"omega in {self.OMEGAS}, prior_cov in {list(self.PRIOR_COVS)}")
        kwargs.setdefault("name", f"HMM + BL ({omega}, {prior_cov})")
        super().__init__(rets, rf, model, **kwargs)
        self.omega, self.prior_cov = omega, prior_cov
        self.sr_target = sr_target / np.sqrt(252)                     # daily Sharpe
        self.confidence = confidence

    def on_refit(self, t):
        """Equilibrium prior, kept fixed between two refits."""
        Sigma_long = self.PRIOR_COVS[self.prior_cov](self.X[:t])
        delta_eq = self.sr_target / np.sqrt(self.w_ref @ Sigma_long @ self.w_ref)
        self.Pi = delta_eq * Sigma_long @ self.w_ref                  # risk premium
        self.tau = 1 / t

    def moments(self, t, p):
        m = self.model
        q, within, between = m.mixture_moments(p)
        Sigma_t = within + between
        if self.omega == "statistical":
            Omega = np.einsum("k,kij->ij", p / m.n_eff, m.covars) + between
        elif self.omega == "conditional":
            s = int(np.argmax(p))
            q, Sigma_t, Omega = m.means[s], m.covars[s], m.covars[s] / m.n_eff[s]
        else:
            Omega = self.tau * (1 - self.confidence) / self.confidence * Sigma_t
        Omega = Omega + 1e-8 * np.eye(len(q))

        # Posterior with P = I. Π is a premium: add the risk-free rate to get total returns
        prior = self.Pi + 100 * self.rf.iloc[t]
        tS = self.tau * Sigma_t
        M = np.linalg.inv(np.linalg.inv(tS) + np.linalg.inv(Omega))   # posterior covariance of μ
        mu_bar = M @ (np.linalg.solve(tS, prior) + np.linalg.solve(Omega, q))
        return mu_bar, Sigma_t + M
